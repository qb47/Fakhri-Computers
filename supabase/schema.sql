-- ═══════════════════════════ row level security ═══════════════════════════
-- The rule everywhere:
--   · the public site may READ listings + settings, and may CREATE form entries
--   · ONLY an admin may read customer personal data, or change anything
-- Everything below is what makes the anon key safe to ship in the browser.

