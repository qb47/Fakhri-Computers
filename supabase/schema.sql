-- admins: the ONLY policy is "read your own row". A signed-in user can ask
-- "am I an admin?" and get one row back (yes) or none (no) — they can never
-- see the admin list, and nobody can write to this table through the API.
-- Rows are added only by the SQL editor (service role), i.e. by you.

drop policy if exists "admins: read own row" on public.admins;
create policy "admins: read own row" on public.admins
  for select using (user_id = auth.uid());

