-- ─────────────────────────────── admin role ───────────────────────────────
-- Admin rights are a ROW IN A TABLE, not an email comparison in a policy.
-- Nothing in the browser can grant this; only this SQL editor (service role) can.

create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text,
  created_at timestamptz not null default now()
);

-- security definer => reads `admins` bypassing RLS, so policies can call it safely.
create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ─────────────────────────────── machines ─────────────────────────────────
-- `uses` is a text[] of use-case ids (everyday, study, business, gaming, ...).
-- screen/kg are `real`, NOT numeric: Postgres returns numeric as a *string*
-- over the API, which would silently break numeric filtering in the app.

create table if not exists public.machines (
  id         text primary key,            -- 'm1', 'm2', ... (generated by the app)
  name       text not null,
  year       int  not null,
  cpu        text not null,
  ram        int  not null,
  ssd        int  not null,
  gpu        text,
  screen     real not null,
  kg         real not null,
  bat        int  not null default 8,
  numpad     boolean not null default false,
  touch      boolean not null default false,
  uses       text[] not null default '{}',
  low        int  not null,
  high       int  not null,
  grade      text not null default 'A-',
  hue        int  not null default 210,
  status     text not null default 'draft'   check (status in ('Available','Sold','Draft')),
  cond       text not null default 'good'    check (cond   in ('budget','good','new')),
  listed     boolean not null default false, -- shows on the "Recently sourced" page
  image_url  text,
  position   int not null default 0,         -- manual ordering
  -- Mirror of the active hold, kept in sync by a trigger below. It lives here,
  -- on a publicly-readable table, so the storefront can show "held until ..."
  -- WITHOUT the public being able to read who holds it (see reservations).
  held_until timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

