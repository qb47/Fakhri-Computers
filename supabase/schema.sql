-- reservations ----------------------------------------------------------
-- NOTE: this row holds a customer's name and phone, so it is NOT publicly
-- readable. The storefront reads `machines.held_until` (no personal data) to
-- show that a machine is held. Only the admin sees who is holding it.

drop policy if exists "reservations: public read" on public.reservations;

drop policy if exists "reservations: admin read" on public.reservations;
create policy "reservations: admin read" on public.reservations
  for select using (public.is_admin());

-- Anyone may place a hold, but only on a machine that is not already held.
-- Without this check a second visitor would silently overwrite the first
-- person's hold (the upsert targets machine_id).
drop policy if exists "reservations: public create" on public.reservations;
create policy "reservations: public create" on public.reservations
  for insert with check (
    not exists (
      select 1 from public.machines
      where id = machine_id and held_until is not null and held_until > now()
    )
  );

drop policy if exists "reservations: admin update" on public.reservations;
create policy "reservations: admin update" on public.reservations
  for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "reservations: admin delete" on public.reservations;
create policy "reservations: admin delete" on public.reservations
  for delete using (public.is_admin());

-- Keep machines.held_until in step with the reservations table. Runs as the
-- table owner, so it can update `machines` even though the visitor who inserted
-- the reservation has no write access to it.
create or replace function public.sync_machine_hold()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (tg_op = 'DELETE') then
    update public.machines set held_until = null where id = old.machine_id;
    return old;
  end if;
  update public.machines set held_until = new.until where id = new.machine_id;
  return new;
end;
$$;

drop trigger if exists reservations_sync_hold on public.reservations;
create trigger reservations_sync_hold
  after insert or update or delete on public.reservations
  for each row execute function public.sync_machine_hold();

